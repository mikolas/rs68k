impl M68000 {
    pub fn init_decode_table(&mut self) {
        self.decode_table = vec![S_ILLEGAL; 0x10000];
        for entry in PACKED_DECODE_TABLE {
            let value = entry.value;
            let mask = entry.mask;
            let state = entry.state;
            let mut cvalue: u16 = 0;
            loop {
                let opcode = value | cvalue;
                if self.decode_table[opcode as usize] == S_ILLEGAL {
                    self.decode_table[opcode as usize] = state;
                }
                cvalue = ((cvalue | mask).wrapping_add(1)) & !mask;
                if cvalue == 0 { break; }
            }
        }
    }
}
